export type Message = keyof typeof idMessages;
export type Interpolation = Record<string, string | number>;
export const languages = ['id', 'en'] as const;
export type Language = typeof languages[number];

export function translate(language: Language, key: Message, values?: Interpolation) {
  return (language === 'id' ? idMessages[key] ?? key : key)
    .replace(/\{(\w+)\}/g, (token, name: string) => String(values?.[name] ?? token));
}
